const dict: Record<Locale, Record<TranslationKey, string>> = { ko, en };

export function t(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  let template = dict[locale][key] ?? dict.ko[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

export function classificationLabel(locale: Locale, cls: MoveClassification): string {
  return t(locale, `cls_${cls}` as TranslationKey);
}

export function classificationComment(locale: Locale, cls: MoveClassification): string {
  return t(locale, `comment_${cls}` as TranslationKey);
}
